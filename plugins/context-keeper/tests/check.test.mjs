test('路径参数在当前仓库外面、又不在 git 仓库里时，把那个目录当作不是 git 仓库的项目查', () => {
  const here = makeRepo({ 'README.md': '# 别的仓库\n' });
  const plain = path.join(here.tmp, 'plain');
  const content = { '.claude/rules/api/nothing.md': '---\npaths: "src/nope/*.ts"\n---\n\n匹配不到。\n', 'src/a.ts': 'export {};\n' };
  for (const [f, text] of Object.entries(content)) {
    fs.mkdirSync(path.dirname(path.join(plain, f)), { recursive: true });
    fs.writeFileSync(path.join(plain, f), text);
  }
  const run = spawnSync('node', [path.join(SCRIPTS, 'check.mjs'), plain, '--json'], { cwd: here.repo, encoding: 'utf8' });
  assert.equal(run.status, 1, run.stderr);
  const r = JSON.parse(run.stdout);
  assert.equal(r.root, plain);
  assert.equal(r.filter, null);
  assert.deepEqual(files(r, 'rule'), ['.claude/rules/api/nothing.md']);
  // 只看其中一个文件：根是它所在的目录
  const one = spawnSync('node', [path.join(SCRIPTS, 'check.mjs'), path.join(plain, 'src', 'a.ts'), '--json'], { cwd: here.repo, encoding: 'utf8' });
  assert.equal(JSON.parse(one.stdout).filter, 'a.ts');
});

test('路径参数是仓库里的软链接时按链接本身过滤，指向仓库外也不报「不在仓库内」', () => {
  const t = makeRepo({ ...CLEAN, 'shared/a.md': '# a\n' });
  const outside = path.join(t.tmp, 'outside');
  fs.mkdirSync(outside);
  fs.symlinkSync(outside, path.join(t.repo, 'ext'));
  fs.symlinkSync(path.join(t.repo, 'shared'), path.join(t.repo, 'alias'));
  const ext = check(t, ['ext']);
  assert.equal(ext.status, 0);
  assert.equal(ext.filter, 'ext/');
  assert.equal(check(t, ['alias']).filter, 'alias/'); // 不跟到 shared/
  // 整个仓库经软链接传进来时照样认得
  fs.symlinkSync(t.repo, path.join(t.tmp, 'link'));
  assert.equal(check(t, [path.join(t.tmp, 'link')]).filter, null);
});
